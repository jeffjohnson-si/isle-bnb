/**
 * A verified owner's own edits, stored by the API. The catalogue above is the
 * seed: anything the owner has published wins over it at start-up.
 */
export interface ListingOverride {
  listingId: string
  price: number | null
  summary: string | null
  description: string | null
  guests: number | null
  bedrooms: number | null
  beds: number | null
  baths: number | null
  amenities: string[] | null
  updatedAt?: string
}

/**
 * Applies owner edits in place, before the app renders. Deliberately not a
 * React context: every page reads these arrays directly, and a host's edit is
 * only meant to be picked up on the next load, not live in other open tabs.
 */
export function applyListingOverrides(overrides: ListingOverride[]) {
  if (!overrides.length) return 0
  const byId = new Map(overrides.map((override) => [override.listingId, override]))
  let applied = 0

  for (const listing of listings) {
    const override = byId.get(listing.id)
    if (!override) continue

    if (override.price !== null) listing.price = override.price
    if (override.summary) listing.summary = override.summary
    if (override.description) listing.description = override.description
    if (override.guests !== null) listing.guests = override.guests
    if (override.bedrooms !== null) listing.bedrooms = override.bedrooms
    if (override.beds !== null) listing.beds = override.beds
    if (override.baths !== null) listing.baths = override.baths
    if (override.amenities?.length) listing.amenities = override.amenities

    applied += 1
  }

  return applied
}
